    // names and game terms, also replaced inside longer pieces of text (longest first, whole words)
    val terms = words.filter { case (k, v) => k.length > 3 && k.head.isUpper && k != v && k.exists(_.isLower) }

    private val pattern = {
        def quote(s : String) = s.flatMap(c => if ("\\^$.|?*+()[]{}".contains(c)) "\\" + c else c.toString)
        java.util.regex.Pattern.compile("\\b(" + terms.keys.toList.sortBy(-_.length).map(quote).mkString("|") + ")(?![\\w'])")
    }

    private val cache = scala.collection.mutable.HashMap[String, String]()

    private def lookup(s : String) : Option[String] = {
        words.get(s).orElse {
            if (s.head.isUpper)
                words.get(s.head.toLower + s.drop(1)).map(t => t.head.toUpper + t.drop(1))
            else
                None
        }
    }

    private def substitute(s : String) : String = {
        val m = pattern.matcher(s)
        val b = new StringBuilder
        var last = 0
        while (m.find()) {
            b ++= s.substring(last, m.start)
            b ++= terms(m.group(1))
            last = m.end
        }
        b ++= s.substring(last)
        b.toString
    }

    private def translate(s : String) : String = {
        val core = s.trim
        if (!core.exists(_.isLetter))
            return s

        val lead = s.takeWhile(_.isWhitespace)
        val trail = s.reverse.takeWhile(_.isWhitespace).reverse

        val punct = core.reverse.takeWhile(c => ".,:;!?)".contains(c)).reverse
        val open = core.takeWhile(_ == '(')
        val bare = core.drop(open.length).dropRight(punct.length)

        lookup(core).map(lead + _ + trail).orElse(
            (if (bare.nonEmpty) lookup(bare) else None).map(lead + open + _ + punct + trail)
        ).getOrElse(substitute(s))
    }

    def text(s : String) : String = cache.getOrElseUpdate(s, translate(s))

